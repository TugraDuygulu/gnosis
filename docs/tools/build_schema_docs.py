#!/usr/bin/env python3
"""Build documentation sources from the measured inventory (standard library only)."""
import html
import json
from pathlib import Path

DOCS = Path(__file__).resolve().parents[1]
DATA = DOCS / 'data' / 'pilot_2026-11-01'
x = json.loads((DATA / 'schema_inventory.json').read_text())
tables = {t['model']: t for t in x['tables'] if t['model']}
by_table = {t['table']: t['model'] for t in tables.values()}
order = ['Program', 'Course', 'Instructor', 'Student', 'POFramework', 'CourseCurriculum', 'ProgramOutcome', 'CourseOffering', 'LearningOutcome', 'Enrollment', 'Assessment', 'LOPOMapping', 'CoursePOContribution', 'Grade', 'AssessmentLOMapping']

def typ(f):
    if f['max_length'] is not None:
        return f"{f['django_type']}({f['max_length']})"
    if f['max_digits'] is not None:
        return f"Decimal({f['max_digits']},{f['decimal_places']})"
    return f['django_type']

out = ['# Application field dictionary', '', 'Generated by `docs/tools/build_schema_docs.py` from the measured inventory. All 15 tables use a surrogate `id`: Django BigAutoField, SQLite INTEGER PRIMARY KEY AUTOINCREMENT. All non-PK columns are NOT NULL except `CourseOffering.po_framework_id` and `Grade.score`. Physical migration column order is preserved in the JSON; this dictionary uses model field order.', '', 'Decimal precision and varchar lengths below describe Django declarations; SQLite affinity does not enforce those limits. Defaults shown are Python model defaults, not SQL DEFAULT clauses. FK columns refer to the target table’s `id`. Composite uniqueness and CHECK constraints are listed in the main document.', '']
for name in order:
    t = tables[name]
    out += [f"## {name} — `{t['table']}`", '', '| Column | Django declaration | Nullable | Key / reference | Python default |', '| --- | --- | --- | --- | --- |']
    for f in t['fields']:
        key = 'PK' if f['primary_key'] else ('UNIQUE' if f['unique'] else '')
        if f['related_table']:
            key = f"FK → `{f['related_table']}.id`; PROTECT in Django"
        default = '—' if f['python_default'] is None else f"`{f['python_default']}`"
        out.append(f"| `{f['column']}` | {typ(f)} | {'yes' if f['null'] else 'no'} | {key or '—'} | {default} |")
    out.append('')
(DATA / 'field_dictionary.md').write_text('\n'.join(out))
out = ['# Physical application index inventory', '', 'Measured after core.0009. SQLite rowid-alias primary keys have no separate PK B-tree. Four single-column UNIQUE constraints and ten composite UNIQUE constraints produce 14 unique autoindexes. Django creates 20 nonunique FK indexes. No additional application indexes are declared.', '', '| Table | Index | Unique | Columns, in index order | Allocated bytes |', '| --- | --- | --- | --- | ---: |']
for t in tables.values():
    for i in t['indexes']:
        out.append(f"| `{t['table']}` | `{i['name']}` | {'yes' if i['unique'] else 'no'} | {', '.join('`'+c['name']+'`' for c in i['columns'])} | {(i['storage'] or {}).get('allocated_bytes', 'unavailable')} |")
(DATA / 'index_inventory.md').write_text('\n'.join(out) + '\n')

diagrams = DOCS / 'diagrams'
diagrams.mkdir(exist_ok=True)
views = {
    'gnosis-erd': order,
    'gnosis-erd-context': ['Program', 'Course', 'Instructor', 'Student', 'POFramework', 'CourseCurriculum', 'CourseOffering', 'Enrollment'],
    'gnosis-erd-assessment': ['CourseCurriculum', 'CourseOffering', 'LearningOutcome', 'Enrollment', 'Assessment', 'AssessmentLOMapping', 'Grade'],
    'gnosis-erd-outcomes': ['POFramework', 'CourseCurriculum', 'ProgramOutcome', 'LearningOutcome', 'CoursePOContribution', 'LOPOMapping'],
}
for stem, names in views.items():
    m = ['erDiagram', '    direction TB']
    dot = ['digraph G {', 'graph [rankdir=TB, bgcolor="white", pad="0.3", nodesep="0.38", ranksep="0.65", splines=polyline, label="Gnosis v0.1 — relational ERD\\nParent end: 1 required or 0..1 optional; child end: 0..*\\nAll id columns are surrogate PKs; FK targets are id; ? means nullable.\\nComposite UNIQUE / CHECK rules: see database_design.md", labelloc=t, fontsize=18, fontname="Helvetica"];', 'node [shape=plain, fontname="Helvetica"];', 'edge [fontname="Helvetica", fontsize=10, color="#64748b", arrowsize=0.7];']
    for name in names:
        t = tables[name]
        m.append(f'    {name} {{')
        rows = [f'<TR><TD BGCOLOR="#17324d"><FONT COLOR="white"><B>{name}</B></FONT></TD></TR>', f'<TR><TD BGCOLOR="#e2e8f0"><FONT POINT-SIZE="11">{t["table"]}</FONT></TD></TR>']
        for f in t['fields']:
            dt = typ(f).replace('(', '_').replace(')', '').replace(',', '_')
            key = ' PK' if f['primary_key'] else (' FK' if f['related_table'] else (' UK' if f['unique'] else ''))
            comment = ' "nullable"' if f['null'] else ''
            m.append(f"        {dt} {f['column']}{key}{comment}")
            label = f"{f['column']}{' ?' if f['null'] else ''} : {typ(f)}{key}"
            rows.append(f'<TR><TD ALIGN="LEFT">{html.escape(label)}</TD></TR>')
        m.append('    }')
        dot.append(f'{name} [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="6">{"".join(rows)}</TABLE>>];')
    for name in names:
        for f in tables[name]['fields']:
            if not f['related_table']:
                continue
            parent = by_table[f['related_table']]
            if parent not in names:
                continue
            cardinality = '|o' if f['null'] else '||'
            m.append(f'    {parent} {cardinality}--o{{ {name} : "{f["column"]}"')
            dot.append(f'{parent} -> {name} [dir=both, arrowtail=none, arrowhead=none, taillabel="{"0..1" if f["null"] else "1"}", headlabel="0..*", labeldistance=2];')
    ranks = {
        'gnosis-erd': [order[:3], order[3:6], order[6:9], order[9:13], order[13:]],
        'gnosis-erd-context': [['Program', 'Course', 'Instructor'], ['Student', 'POFramework', 'CourseCurriculum'], ['CourseOffering', 'Enrollment']],
        'gnosis-erd-assessment': [['CourseCurriculum', 'CourseOffering'], ['LearningOutcome', 'Enrollment', 'Assessment'], ['AssessmentLOMapping', 'Grade']],
        'gnosis-erd-outcomes': [['POFramework', 'CourseCurriculum'], ['ProgramOutcome', 'LearningOutcome'], ['CoursePOContribution', 'LOPOMapping']],
    }
    for rank in ranks[stem]:
        dot.append('{rank=same; ' + '; '.join(rank) + ';}')
    dot.append('}')
    (diagrams / f'{stem}.mmd').write_text('\n'.join(m)+'\n')
    (diagrams / f'{stem}.dot').write_text('\n'.join(dot)+'\n')
print('Generated four Mermaid/DOT views, field dictionary, and index inventory.')
